import type { ReactNode, SVGProps } from "react";

// Small inline icons (24x24 stroke icons). They are decorative: the text next to them always carries the meaning,
// so every icon is aria-hidden.

type IconProps = Omit<SVGProps<SVGSVGElement>, "children">;

function Icon({ children, className = "h-5 w-5", ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={`shrink-0 ${className}`}
      {...rest}
    >
      {children}
    </svg>
  );
}

